import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** orval이 훅을 한꺼번에 쓰는 폴더. */
const HOOK_DIR = 'src/api';

/** orval이 타입을 쓰는 폴더. 라우트 전용 타입은 이 아래 `<라우트>/`에, 공통 타입은 바로 아래에 쓴다. */
const TYPE_DIR = 'src/type';

/** orval이 만든 파일 머리말. 직접 쓴 파일을 덮어쓰지 않으려고 이 문구로 구분한다. */
const GENERATED_MARK = 'Generated by orval';

/** `src/routes/ideas/type` → `@/routes/ideas/type` */
const toAlias = (path) => `@/${path.replace(/^src\//, '')}`;

/** 파일에서 내보내는 이름들. */
const exportedNames = (code) =>
  [...code.matchAll(/export (?:interface|type|const|enum) (\w+)/g)].map(([, name]) => name);

/** 직접 쓴 파일을 덮어쓰게 되면 멈춘다. */
const assertWritable = (path) => {
  if (existsSync(path) && !readFileSync(path, 'utf8').includes(GENERATED_MARK)) {
    throw new Error(`직접 쓴 파일을 덮어쓰게 됩니다: ${path}`);
  }
};

/**
 * 라우트 전용 타입을 `src/type/<라우트>/`에서 그 라우트의 `type/` 폴더로 옮긴다.
 * 공통 타입을 가리키던 `../이름`은 `@/type/이름`으로 바꾼다. 옮긴 타입 이름을 돌려준다.
 */
const moveRouteTypes = (route, routeTypeDir) => {
  const from = join(TYPE_DIR, route);
  if (!existsSync(from)) {
    return { names: new Set(), movedFiles: [] };
  }
  // 여러 라우트가 쓰는 라우트(내 계정 등)는 `src/type/` 바로 아래로 옮기므로, 공통 `index.ts`를 덮어쓰지 않는다.
  const isCommon = routeTypeDir === TYPE_DIR;
  const names = new Set();
  const movedFiles = [];
  mkdirSync(routeTypeDir, { recursive: true });
  for (const file of readdirSync(from)) {
    if (isCommon && file === 'index.ts') {
      continue;
    }
    const code = readFileSync(join(from, file), 'utf8').replaceAll("from '../", "from '@/type/");
    const to = join(routeTypeDir, file);
    assertWritable(to);
    writeFileSync(to, code);
    if (file !== 'index.ts') {
      movedFiles.push(file);
      if (!isCommon) {
        exportedNames(code).forEach((name) => names.add(name));
      }
    }
  }
  rmSync(from, { recursive: true });
  return { names, movedFiles };
};

/** 훅 파일의 `import { ... } from '../type'`를 라우트 전용 타입과 공통 타입으로 나눈다. */
const splitTypeImports = (code, routeNames, routeTypeAlias) =>
  code.replace(/import (type )?\{([^}]*)\} from '\.\.\/type';/g, (_match, typeKeyword = '', list) => {
    const names = list
      .split(',')
      .map((name) => name.trim())
      .filter(Boolean);
    const own = names.filter((name) => routeNames.has(name));
    const shared = names.filter((name) => !routeNames.has(name));
    const statement = (specifier, group) => `import ${typeKeyword}{ ${group.join(', ')} } from '${specifier}';`;
    return [own.length > 0 && statement(routeTypeAlias, own), shared.length > 0 && statement('@/type', shared)]
      .filter(Boolean)
      .join('\n');
  });

/** `src/api/<라우트>.ts`를 그 라우트의 `api/use-<라우트>.ts`로 옮기고 import를 맞춘다. */
const moveRouteHooks = (route, apiDir, routeNames, routeTypeAlias) => {
  const from = join(HOOK_DIR, `${route}.ts`);
  if (!existsSync(from)) {
    return;
  }
  const code = splitTypeImports(readFileSync(from, 'utf8'), routeNames, routeTypeAlias).replaceAll(
    "'./mutator'",
    "'@/api/mutator'"
  );
  const to = join(apiDir, `use-${route}.ts`);
  mkdirSync(apiDir, { recursive: true });
  assertWritable(to);
  writeFileSync(to, code);
  rmSync(from);
};

/**
 * 옮겨 간 라우트 폴더를 가리키던 줄을 공통 타입 `index.ts`에서 뺀다.
 * `src/type/` 바로 아래로 옮긴 라우트는 그 줄을 옮긴 파일들의 export로 바꾼다.
 */
const updateCommonIndex = (movedByRoute) => {
  const indexPath = join(TYPE_DIR, 'index.ts');
  if (!existsSync(indexPath)) {
    return;
  }
  const lines = readFileSync(indexPath, 'utf8')
    .split('\n')
    .flatMap((line) => {
      const route = [...movedByRoute.keys()].find((name) => line === `export * from './${name}';`);
      if (!route) {
        return [line];
      }
      return movedByRoute.get(route).map((file) => `export * from './${file.replace(/\.ts$/, '')}';`);
    });
  writeFileSync(indexPath, lines.join('\n'));
};

/** `dir` 아래에서 orval이 만든 파일(머리말로 구분)의 경로를 모은다. */
const collectGeneratedFiles = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      return collectGeneratedFiles(path);
    }
    return path.endsWith('.ts') && readFileSync(path, 'utf8').includes(GENERATED_MARK) ? [path] : [];
  });

/** 생성 파일을 커밋 때 적용되는 포맷으로 미리 맞춘다. 다시 생성해도 커밋과 diff가 생기지 않게 한다. */
const formatGeneratedFiles = () => {
  const files = collectGeneratedFiles('src');
  if (files.length > 0) {
    execFileSync('pnpm', ['exec', 'oxfmt', ...files], { stdio: 'inherit' });
  }
};

/**
 * 인자는 `<라우트>=<api 폴더>` 형식이다. orval이 뒤에 붙이는 파일 경로 인자는 무시한다.
 * 라우트의 훅은 `<api 폴더>/use-<라우트>.ts`로, 전용 타입은 같은 위계의 `type/` 폴더로 옮긴다.
 */
const placeGeneratedFiles = (args) => {
  const routes = args.map((arg) => arg.split('=')).filter(([, apiDir]) => apiDir);
  const movedByRoute = new Map();
  for (const [route, apiDir] of routes) {
    const routeTypeDir = apiDir.replace(/\/api$/, '/type');
    const { names, movedFiles } = moveRouteTypes(route, routeTypeDir);
    movedByRoute.set(route, routeTypeDir === TYPE_DIR ? movedFiles : []);
    moveRouteHooks(route, apiDir, names, toAlias(routeTypeDir));
  }
  updateCommonIndex(movedByRoute);
  formatGeneratedFiles();
};

placeGeneratedFiles(process.argv.slice(2));
